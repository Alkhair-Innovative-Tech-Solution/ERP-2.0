"""
Script: seed_certifications_from_sheet.py
Purpose: Read the Exam/Certification spreadsheet and create Certification records
         in the certification-service for students whose certifications were issued.

The Google Sheet has multiple tabs (e.g. DS11, CF01) each with:
  ID | STUDENT NAME | CONTACT NO | ATTENDANCE STATUS | PAPER STATUS | REMARKS | PAPER MARKS | CERTIFICATED ISSUE

Steps:
1. Download each sheet tab as CSV (using the tab GID), look for rows where CERTIFICATED ISSUE == 'Issue'
2. Use the Student ID to find the student's UUID from auth-service DB
3. Use the Student ID to find the Course from course-service DB (via course_code)
4. Create a Certification record in the certification-service DB

Usage (inside cert-service container):
  python seed_certifications_from_sheet.py

Dependencies:
  - student_mapping.json  (email -> UUID from auth-service seeding step)
  - course_mapping.json   (course_code -> course UUID from course-service)
  - The same Google Sheets ID / GIDs for the exam sheet

Place this script in: certification-service/
"""

