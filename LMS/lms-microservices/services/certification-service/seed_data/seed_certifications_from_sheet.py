def fetch_csv_by_sheet_name(spreadsheet_id, sheet_name):
    """Download a Google Sheet tab as CSV using sheet name (no GID needed)."""
    url = f"https://docs.google.com/spreadsheets/d/{spreadsheet_id}/gviz/tq?tqx=out:csv&sheet={sheet_name}"
    try:
        response = urllib.request.urlopen(url, timeout=30)
        content = response.read().decode('utf-8-sig')
        rows = list(csv.reader(io.StringIO(content)))
        if not rows:
            return []
        # Find header row (the one that has "ID" or "STUDENT NAME")
        header_row_idx = None
        for i, row in enumerate(rows):
            normalized = [c.strip().upper() for c in row]
            if 'ID' in normalized and 'STUDENT NAME' in normalized:
                header_row_idx = i
                break
        if header_row_idx is None:
            return []
        headers = [c.strip().upper() for c in rows[header_row_idx]]
        result = []
        for row in rows[header_row_idx + 1:]:
            if len(row) < len(headers):
                row += [''] * (len(headers) - len(row))
            result.append(dict(zip(headers, [c.strip() for c in row])))
        return result
    except Exception as e:
        print(f"  Error fetching sheet '{sheet_name}': {e}")
        return []

def extract_course_code(student_id_val):
    """Extract course code from student ID like AIT25-DS11-0872 -> DS1"""
    parts = student_id_val.split('-')
    if len(parts) >= 2:
        code_sec = parts[1]
        match = re.match(r'^([A-Za-z]+\d*)([1-9]\d*)$', code_sec)
        if match:
            return match.group(1)
        return code_sec
    return ''

def make_cert_number():
    """Generate a unique cert number."""
    return f"AIT-CERT-{uuid.uuid4().hex[:8].upper()}"

def make_verification_code():
    """Generate a unique verification code."""
    return uuid.uuid4().hex[:16].upper()

